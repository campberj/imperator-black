{
    var variants = argList.Where(a => a.Contains('=') && a.EndsWith(".json"))
        .Select(a => (a[..a.IndexOf('=')], ContentSet.LoadFile(a[(a.IndexOf('=') + 1)..]))).ToList();
    Console.Write(Compare.Run(variants, ArgIntStatic(argList, "--n", 20000), ArgIntStatic(argList, "--seed", 1)));
    return;
}
static int ArgIntStatic(List<string> list, string name, int def)
{
    int i = list.IndexOf(name);
    return i >= 0 && i + 1 < list.Count && int.TryParse(list[i + 1], out var v) ? v : def;
}
string? outPath = argList.FirstOrDefault(a => !a.StartsWith("--") && (argList.IndexOf(a) == 0 || !argList[argList.IndexOf(a) - 1].StartsWith("--")));
