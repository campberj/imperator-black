static string P(double p) => p < 0.0005 ? "—" : $"{p * 100:0}%";

Soldier Make(string name, int q, string armour, string weapon, string melee = "knife",
    bool leader = false, bool medic = false, bool voidTrained = false) =>
    Soldier.Generic(name, q, content.ArmourById(armour).Value, content.Ranged(weapon), content.Melee(melee), leader, medic, voidTrained);

void ShotTables()
{
    md.AppendLine("## 1. One shot against a fresh target (exact)");
    md.AppendLine();
    md.AppendLine("Shooter Q1, no other modifiers; target in Light cover (net modifier 0, so 15/36 ≈ 42% to hit). \"Out\" = Down, Bleeding, Critical or Dead.");
    md.AppendLine();
    md.AppendLine("| Weapon | Armour | Hit | Suppression only | Wounded | Out | Dead |");
    md.AppendLine("|---|---|---|---|---|---|---|");
    foreach (var w in content.Weapons.Ranged)
    foreach (int armour in new[] { 0, 1, 2, 3 })
    {
        var o = Shooting.Odds(core, 0, w.DamageDice, armour, w.Ap);
        double hit = 1 - o[Outcome.Miss];
        double outP = o[Outcome.Down] + o[Outcome.Bleeding] + o[Outcome.Critical] + o[Outcome.Dead];
        md.AppendLine($"| {w.Name} | {armour} | {P(hit)} | {P(o[Outcome.Suppression] + o[Outcome.NoEffect])} | {P(o[Outcome.Wounded])} | {P(outP)} | {P(o[Outcome.Dead])} |");
    }
    md.AppendLine();
    md.AppendLine("\"Suppression only\" includes hits stepped down to no effect.");
    md.AppendLine();
}

void HitChanceTable()
{
    md.AppendLine("## 2. Chance to hit (exact)");
    md.AppendLine();
    md.AppendLine("| Net modifier | 2d6 + mod ≥ 8 |");
    md.AppendLine("|---|---|");
    for (int mod = -4; mod <= 4; mod++)
    {
        var o = Shooting.Odds(core, mod, new DiceSpec(1, 2), 0, 0);
        md.AppendLine($"| {(mod >= 0 ? "+" : "")}{mod} | {P(1 - o[Outcome.Miss])} |");
    }
    md.AppendLine();
    md.AppendLine("Net modifier = Q + Aim − cover − Suppression − other penalties. Q1 in the open: +1. Q1 at Light cover: 0. Q2 at Heavy cover: 0. Q1 Overwatch at a model in the open: 0.");
    md.AppendLine();
}

void CloseCombatTable()
{
    md.AppendLine("## 3. Close combat duels (Monte Carlo)");
    md.AppendLine();
    md.AppendLine("Attacker charges. Both use the default break rule (break only after losing while Wounded or at 3+ Suppression; combat ends only if both break).");
    md.AppendLine();
    md.AppendLine("| Attacker | Defender | Attacker wins | Defender wins | Both broke | Avg exchanges | Loser dead |");
    md.AppendLine("|---|---|---|---|---|---|---|");
    var cases = new (string A, Func<Soldier> MakeA, string D, Func<Soldier> MakeD)[]
    {
        ("Q1 A1 knife", () => Make("a", 1, "flak", "carbine"), "Q1 A1 knife", () => Make("d", 1, "flak", "carbine")),
        ("Q2 A2 knife (void assault)", () => Make("a", 2, "void_plate", "carbine"), "Q1 A1 knife (enforcer)", () => Make("d", 1, "flak", "smg")),
        ("Q1 A1 breaching tool", () => Make("a", 1, "flak", "shotgun", "breaching_tool"), "Q2 A2 knife", () => Make("d", 2, "void_plate", "carbine")),
        ("Q2 A2 knife", () => Make("a", 2, "void_plate", "carbine"), "Q0 A0 unarmed (crew)", () => Make("d", 0, "none", "sidearm", "unarmed")),
        ("Q1 A1 knife", () => Make("a", 1, "flak", "carbine"), "Q2 A3 knife (heavy)", () => Make("d", 2, "heavy", "carbine")),
        ("Q1 A1 unarmed", () => Make("a", 1, "flak", "carbine", "unarmed"), "Q1 A3 unarmed", () => Make("d", 1, "heavy", "carbine", "unarmed")),
    };
    var rng = new Rng(seed);
    foreach (var c in cases)
    {
        int aw = 0, dw = 0, bb = 0, totalEx = 0, dead = 0;
        for (int i = 0; i < n; i++)
        {
            var a = c.MakeA(); var d = c.MakeD();
            var r = CloseCombat.Fight(rng, core, a, d, charging: true);
            totalEx += r.Exchanges;
            switch (r.End)
            {
                case CombatEnd.AttackerWon: aw++; if (d.Status == Status.Dead) dead++; break;
                case CombatEnd.DefenderWon: dw++; if (a.Status == Status.Dead) dead++; break;
                default: bb++; break;
            }
        }
        md.AppendLine($"| {c.A} | {c.D} | {P(aw / (double)n)} | {P(dw / (double)n)} | {P(bb / (double)n)} | {totalEx / (double)n:0.0} | {P(dead / (double)Math.Max(1, aw + dw))} |");
    }
    md.AppendLine();
}

void FragTable()
{
    md.AppendLine("## 4. Frag grenade on target (Monte Carlo)");
    md.AppendLine();
    md.AppendLine("| Armour | Position | Suppression only | Wounded | Out |");
    md.AppendLine("|---|---|---|---|---|");
    var frag = content.Thrown("frag");
    var rng = new Rng(seed + 1);
    foreach (int armour in new[] { 0, 1, 2, 3 })
    foreach (var (label, cover, confined) in new[] { ("Open area", Cover.Open, false), ("Heavy cover", Cover.Heavy, false), ("Confined room", Cover.Open, true) })
    {
        int sup = 0, wnd = 0, outC = 0;
        for (int i = 0; i < n; i++)
        {
            var s = Soldier.Generic("t", 1, armour, content.Ranged("carbine"), content.Melee("knife")); s.Cover = cover;
            Grenades.Frag(rng, core, frag, new[] { s }, confined);
            if (!s.IsActive) outC++; else if (s.Wounded) wnd++; else sup++;
        }
        md.AppendLine($"| {armour} | {label} | {P(sup / (double)n)} | {P(wnd / (double)n)} | {P(outC / (double)n)} |");
    }
    md.AppendLine();
}

void FirefightTable()
{
    md.AppendLine("## 5. Open-ground firefights (Monte Carlo)");
    md.AppendLine();
    md.AppendLine("Abstract model: cover is a state, range is sampled 6–24\" per shot, both sides use the same policy, 8 rounds, no reactions. Compare with the A War of Worlds prototype findings.");
    md.AppendLine();
    md.AppendLine("| Matchup | Side A wins | Side B wins | Draw |");
    md.AppendLine("|---|---|---|---|");
    var rng = new Rng(seed + 2);

    List<Soldier> Team(int count, int q, string armour, string weapon, bool withLeader = true) =>
        Enumerable.Range(0, count).Select(i => Make($"m{i}", q, armour, weapon, leader: withLeader && i == 0)).ToList();

    void Row(string label, Func<List<Soldier>> a, Func<List<Soldier>> b, double aOpen = 0.2, double bOpen = 0.2, double aHeavy = 0.3, double bHeavy = 0.3)
    {
        int wa = 0, wb = 0, dr = 0;
        for (int i = 0; i < n; i++)
        {
            var sa = a(); var sb = b();
            Firefight.ScatterCover(rng, sa, aOpen, aHeavy);
            Firefight.ScatterCover(rng, sb, bOpen, bHeavy);
            switch (new Firefight(rng, core, sa, sb).Run())
            {
                case FightWinner.A: wa++; break;
                case FightWinner.B: wb++; break;
                default: dr++; break;
            }
        }
        md.AppendLine($"| {label} | {P(wa / (double)n)} | {P(wb / (double)n)} | {P(dr / (double)n)} |");
    }

    Row("4 Q1 rifles vs 4 Q1 rifles (all Flak)", () => Team(4, 1, "flak", "rifle"), () => Team(4, 1, "flak", "rifle"));
    Row("4 Q2 rifles vs 4 Q1 rifles", () => Team(4, 2, "flak", "rifle"), () => Team(4, 1, "flak", "rifle"));
    Row("4 Q1 rifles vs 5 Q1 rifles", () => Team(4, 1, "flak", "rifle"), () => Team(5, 1, "flak", "rifle"));
    Row("Patrol Contact: prototype fireteam vs patrol", () => new List<Soldier>
        {
            Make("TL", 2, "composite", "rifle", leader: true), Make("Gunner", 1, "flak", "lmg"),
            Make("Medic", 1, "flak", "rifle", medic: true), Make("Marksman", 1, "flak", "dmr"),
        },
        () => new List<Soldier>
        {
            Make("Ldr", 1, "flak", "rifle", leader: true), Make("Gun", 1, "flak", "lmg"),
            Make("R1", 1, "flak", "rifle"), Make("R2", 1, "flak", "rifle"), Make("Tpr", 1, "flak", "smg"),
        });
    Row("Pillar 1: 4 Q2 in cover vs 6 Q0 in the open", () => Team(4, 2, "flak", "rifle"), () => Team(6, 0, "flak", "rifle"),
        aOpen: 0.0, bOpen: 1.0, aHeavy: 0.5, bHeavy: 0.0);
    md.AppendLine();
}

void RoomClearTable()
{
    md.AppendLine("## 6. Clearing a compartment (Monte Carlo)");
    md.AppendLine();
    md.AppendLine("Four Void Assault troopers (Q2, Void plate, carbines, Void-trained, leader) clear a 6\"×6\" compartment held by three Freespace asset security guards (Q1, Flak, two carbines and a shotgun) in Light cover. Up to 3 rounds; attackers move first.");
    md.AppendLine();
    md.AppendLine("| Entry | Defenders | Cleared R1 | Cleared by R3 | Repulsed | Attackers out (avg) | Attackers dead (avg) | Defenders out (avg) |");
    md.AppendLine("|---|---|---|---|---|---|---|---|");
    var rng = new Rng(seed + 3);
    foreach (var overwatch in new[] { true, false })
    foreach (var method in Enum.GetValues<EntryMethod>())
    {
        int r1 = 0, cleared = 0, repulsed = 0; double attOut = 0, attDead = 0, defOut = 0;
        for (int i = 0; i < n; i++)
        {
            var att = Enumerable.Range(0, 4).Select(k => Make($"VAT{k}", 2, "void_plate", "carbine", leader: k == 3, voidTrained: true)).ToList();
            var def = new List<Soldier> { Make("G1", 1, "flak", "carbine"), Make("G2", 1, "flak", "carbine"), Make("G3", 1, "flak", "shotgun") };
            var sim = new RoomClear(rng, content, att, def, method, overwatch);
            var o = sim.Run();
            if (o == RoomOutcome.Cleared) { cleared++; if (sim.RoundCleared == 1) r1++; }
            if (o == RoomOutcome.Repulsed) repulsed++;
            attOut += att.Count(s => !s.IsActive);
            attDead += att.Count(s => s.Status == Status.Dead);
            defOut += def.Count(s => !s.IsActive);
        }
        string mLabel = method switch
        {
            EntryMethod.Dynamic => "Open door, go in",
            EntryMethod.FlashFirst => "Flashbang, then in",
            EntryMethod.FragFirst => "Frag, then in",
            _ => "Breach charge + flashbang",
        };
        md.AppendLine($"| {mLabel} | {(overwatch ? "On Overwatch" : "Unready")} | {P(r1 / (double)n)} | {P(cleared / (double)n)} | {P(repulsed / (double)n)} | {attOut / n:0.00} | {attDead / n:0.00} | {defOut / n:0.00} |");
    }
    md.AppendLine();
    md.AppendLine("Simplifications: no positions inside the room; every defender sees every attacker who has entered; attackers outside are out of sight; attackers do not react; a grenade that misses has no effect inside.");
    md.AppendLine();
}

void Experiments()
{
    md.AppendLine("## 7. Experiments: candidate rule changes (not current rules)");
    md.AppendLine();
    md.AppendLine("### 7a. Close-quarters bonus: extra wound rows for shots inside the compartment");
    md.AppendLine();
    md.AppendLine("Same setup as section 6, defenders on Overwatch.");
    md.AppendLine();
    md.AppendLine("| Close-quarters bonus | Entry | Cleared R1 | Cleared by R3 | Repulsed | Attackers out (avg) | Attackers dead (avg) | Defenders out (avg) |");
    md.AppendLine("|---|---|---|---|---|---|---|---|");
    var rng = new Rng(seed + 4);
    foreach (int bonus in new[] { 0, 1, 2 })
    foreach (var method in new[] { EntryMethod.Dynamic, EntryMethod.FlashFirst, EntryMethod.FragFirst, EntryMethod.BreachAndFlash })
    {
        int r1 = 0, cleared = 0, repulsed = 0; double attOut = 0, attDead = 0, defOut = 0;
        for (int i = 0; i < n; i++)
        {
            var att = Enumerable.Range(0, 4).Select(k => Make($"VAT{k}", 2, "void_plate", "carbine", leader: k == 3, voidTrained: true)).ToList();
            var def = new List<Soldier> { Make("G1", 1, "flak", "carbine"), Make("G2", 1, "flak", "carbine"), Make("G3", 1, "flak", "shotgun") };
            var sim = new RoomClear(rng, content, att, def, method, true) { CloseQuartersRows = bonus };
            var o = sim.Run();
            if (o == RoomOutcome.Cleared) { cleared++; if (sim.RoundCleared == 1) r1++; }
            if (o == RoomOutcome.Repulsed) repulsed++;
            attOut += att.Count(s => !s.IsActive);
            attDead += att.Count(s => s.Status == Status.Dead);
            defOut += def.Count(s => !s.IsActive);
        }
        md.AppendLine($"| +{bonus} | {method} | {P(r1 / (double)n)} | {P(cleared / (double)n)} | {P(repulsed / (double)n)} | {attOut / n:0.00} | {attDead / n:0.00} | {defOut / n:0.00} |");
    }
    md.AppendLine();

    md.AppendLine("### 7b. Close-quarters bonus on a single shot (exact)");
    md.AppendLine();
    md.AppendLine("Shooter Q1 vs Light cover, as section 1, with +1 wound row.");
    md.AppendLine();
    md.AppendLine("| Weapon | Armour | Wounded | Out | Dead |");
    md.AppendLine("|---|---|---|---|---|");
    foreach (var id in new[] { "sidearm", "carbine", "shotgun" })
    foreach (int armour in new[] { 0, 1, 2 })
    {
        var w = content.Ranged(id);
        var o = Shooting.Odds(core, 0, w.DamageDice, Math.Max(0, armour - 1), w.Ap); // +1 row == one less armour step when armour > 0
        if (armour == 0)
        {
            // +1 row against no armour: compute directly
            o = Enum.GetValues<Outcome>().ToDictionary(x => x, _ => 0.0);
            var pmf = w.DamageDice.Pmf();
            for (int a = 1; a <= 6; a++) for (int b = 1; b <= 6; b++)
            {
                if (!Shooting.IsHit(core, a, b, 0)) { o[Outcome.Miss] += 1.0 / 36; continue; }
                bool crit = a == 6 && b == 6;
                foreach (var (dmg, p) in pmf) o[Wounds.Classify(Math.Min(10, Wounds.FinalRow(core, dmg, crit, 0, 0) + 1))] += p / 36;
            }
        }
        double outP = o[Outcome.Down] + o[Outcome.Bleeding] + o[Outcome.Critical] + o[Outcome.Dead];
        md.AppendLine($"| {w.Name} | {armour} | {P(o[Outcome.Wounded])} | {P(outP)} | {P(o[Outcome.Dead])} |");
    }
    md.AppendLine();

    md.AppendLine("### 7c. Decisive blows in close combat");
    md.AppendLine();
    md.AppendLine("Winner adds +1 wound row when it wins the exchange by the margin shown or more.");
    md.AppendLine();
    md.AppendLine("| Margin | Matchup | Attacker wins | Defender wins | Both broke | Avg exchanges | Loser dead |");
    md.AppendLine("|---|---|---|---|---|---|---|");
    var crng = new Rng(seed + 5);
    var cases = new (string L, Func<Soldier> A, Func<Soldier> D)[]
    {
        ("Q1 A1 knife vs Q1 A1 knife", () => Make("a", 1, "flak", "carbine"), () => Make("d", 1, "flak", "carbine")),
        ("Q2 A2 knife vs Q1 A1 knife", () => Make("a", 2, "void_plate", "carbine"), () => Make("d", 1, "flak", "smg")),
        ("Q1 A1 breaching tool vs Q2 A2 knife", () => Make("a", 1, "flak", "shotgun", "breaching_tool"), () => Make("d", 2, "void_plate", "carbine")),
    };
    foreach (int margin in new[] { 0, 4, 3 })
    foreach (var c in cases)
    {
        int aw = 0, dw = 0, bb = 0, ex = 0, dead = 0;
        for (int i = 0; i < n; i++)
        {
            var a = c.A(); var d = c.D();
            var r = CloseCombat.Fight(crng, core, a, d, true, decisiveMargin: margin);
            ex += r.Exchanges;
            if (r.End == CombatEnd.AttackerWon) { aw++; if (d.Status == Status.Dead) dead++; }
            else if (r.End == CombatEnd.DefenderWon) { dw++; if (a.Status == Status.Dead) dead++; }
            else bb++;
        }
        md.AppendLine($"| {(margin == 0 ? "none" : margin + "+")} | {c.L} | {P(aw / (double)n)} | {P(dw / (double)n)} | {P(bb / (double)n)} | {ex / (double)n:0.0} | {P(dead / (double)Math.Max(1, aw + dw))} |");
    }
    md.AppendLine();
}

