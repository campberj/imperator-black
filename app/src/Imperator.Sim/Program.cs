var argList = args.ToList();
if (argList.Contains("--values"))
{
    var report = Values.Report(ContentSet.LoadDefault(Directory.GetCurrentDirectory()), ArgIntStatic(argList, "--n", 20000), ArgIntStatic(argList, "--seed", 1));
